"""Compile structured slides into a classroom-ready ``.pptx`` file.

Design decisions are driven by the requirement that the deck must be usable
immediately in a lecture hall: 16:9, white background, Arial, a hard floor of
24pt body text, and a maximum of five bullets per slide. ``python-pptx`` builds
the file in memory and returns bytes, so the service stays stateless and there
is nothing to clean up between requests.
"""

from __future__ import annotations

import io
from datetime import date

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

from app.models import Grounding, Slide

# Brand tokens (kept in sync with frontend/design.md).
_INK = RGBColor(0x0F, 0x17, 0x2A)
_MUTED = RGBColor(0x64, 0x74, 0x8B)
_ACCENT = RGBColor(0x25, 0x63, 0xEB)
_WARN = RGBColor(0xB4, 0x53, 0x09)

_SLIDE_WIDTH = Inches(13.333)
_SLIDE_HEIGHT = Inches(7.5)
_MAX_BULLETS = 5
_MIN_BODY_PT = 24.0


def build_presentation(
    slides: list[Slide],
    *,
    deck_title: str,
    subtitle: str = "",
    include_sources_slide: bool = True,
) -> bytes:
    """Return the bytes of a generated ``.pptx`` deck."""

    presentation = Presentation()
    presentation.slide_width = _SLIDE_WIDTH
    presentation.slide_height = _SLIDE_HEIGHT

    _add_title_slide(presentation, deck_title, subtitle)
    for slide in slides:
        _add_content_slide(presentation, slide)

    if include_sources_slide:
        _add_sources_slide(presentation, slides)

    buffer = io.BytesIO()
    presentation.save(buffer)
    return buffer.getvalue()


def _blank_layout(presentation: Presentation):
    # Layout 6 is the canonical blank layout in the default template.
    return presentation.slide_layouts[6]


def _style_run(run, *, size: float, bold: bool = False, color: RGBColor = _INK) -> None:
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color


def _write(paragraph, text: str, *, size: float, bold: bool = False, color: RGBColor = _INK) -> None:
    """Replace a paragraph's text with a single consistently styled run."""
    run = paragraph.add_run()
    run.text = text
    _style_run(run, size=size, bold=bold, color=color)


def _add_title_slide(presentation: Presentation, title: str, subtitle: str) -> None:
    slide = presentation.slides.add_slide(_blank_layout(presentation))

    box = slide.shapes.add_textbox(Inches(1.0), Inches(2.4), Inches(11.3), Inches(1.6))
    frame = box.text_frame
    frame.word_wrap = True
    paragraph = frame.paragraphs[0]
    paragraph.alignment = PP_ALIGN.CENTER
    _write(paragraph, title, size=44, bold=True)

    subtitle_text = subtitle or f"Generated by Edezee · {date.today().isoformat()}"
    sub_box = slide.shapes.add_textbox(Inches(1.0), Inches(4.1), Inches(11.3), Inches(0.8))
    sub_frame = sub_box.text_frame
    sub_frame.word_wrap = True
    sub_paragraph = sub_frame.paragraphs[0]
    sub_paragraph.alignment = PP_ALIGN.CENTER
    _write(sub_paragraph, subtitle_text, size=28, color=_MUTED)


def _add_content_slide(presentation: Presentation, slide: Slide) -> None:
    pptx_slide = presentation.slides.add_slide(_blank_layout(presentation))

    title_box = pptx_slide.shapes.add_textbox(Inches(0.7), Inches(0.45), Inches(11.9), Inches(1.0))
    title_frame = title_box.text_frame
    title_frame.word_wrap = True
    _write(title_frame.paragraphs[0], slide.slide_title, size=36, bold=True)

    if slide.degraded:
        flag_box = pptx_slide.shapes.add_textbox(Inches(0.7), Inches(1.35), Inches(11.9), Inches(0.4))
        _write(
            flag_box.text_frame.paragraphs[0],
            "Automatically generated content unavailable — review this slide.",
            size=14,
            bold=True,
            color=_WARN,
        )

    body_top = Inches(2.0)
    body_box = pptx_slide.shapes.add_textbox(Inches(0.9), body_top, Inches(11.5), Inches(4.2))
    body_frame = body_box.text_frame
    body_frame.word_wrap = True

    bullets = slide.bullet_points[:_MAX_BULLETS]
    body_size = _fit_body_size(bullets)
    for index, bullet in enumerate(bullets):
        paragraph = body_frame.paragraphs[0] if index == 0 else body_frame.add_paragraph()
        paragraph.level = 0
        paragraph.space_after = Pt(12)
        _write(paragraph, f"•  {bullet}", size=body_size)

    if slide.speaker_notes:
        notes_frame = pptx_slide.notes_slide.notes_text_frame
        notes_frame.text = slide.speaker_notes


def _fit_body_size(bullets: list[str]) -> float:
    """Shrink body text only as far as needed, never below the 24pt floor."""

    longest = max((len(bullet) for bullet in bullets), default=0)
    if longest > 220 or len(bullets) >= 5:
        return _MIN_BODY_PT
    if longest > 160:
        return 26.0
    return 28.0


def _add_sources_slide(presentation: Presentation, slides: list[Slide]) -> None:
    grounded = [slide for slide in slides if slide.sources]
    slide = presentation.slides.add_slide(_blank_layout(presentation))

    title_box = slide.shapes.add_textbox(Inches(0.7), Inches(0.45), Inches(11.9), Inches(0.9))
    _write(title_box.text_frame.paragraphs[0], "Sources & Method", size=36, bold=True)

    body_box = slide.shapes.add_textbox(Inches(0.9), Inches(1.7), Inches(11.5), Inches(4.8))
    frame = body_box.text_frame
    frame.word_wrap = True

    lines: list[str] = []
    if grounded:
        for content_slide in grounded:
            lines.append(f"{content_slide.slide_title}:")
            for source in content_slide.sources[:3]:
                lines.append(f"    {source}")
    else:
        lines.append("Web research was not used for this deck.")
        lines.append("Slide content reflects the drafting model's general knowledge.")
    lines.append("")
    lines.append("Review before teaching: automated content can contain errors.")

    for index, line in enumerate(lines[:16]):
        paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        _write(paragraph, line, size=14 if line.startswith("    ") else 16, color=_MUTED)


def grounding_summary(slides: list[Slide]) -> dict[str, int]:
    """Count slides by grounding source; used by the API and the eval harness."""

    summary = {level.value: 0 for level in Grounding}
    for slide in slides:
        summary[slide.grounding.value] += 1
    return summary
